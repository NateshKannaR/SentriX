export function getInitialSeedIncidents(): Incident[] {
  const result: Incident[] = [];

  for (const item of rawSeedIncidents) {
    const intel = analyzeIncidentIntelligence({
      category: item.category,
      peopleAffected: item.peopleAffected,
      title: item.title,
      description: item.description,
      location: item.location,
      createdAt: item.createdAt,
    });

    // Check for duplicate among already created ones
    const duplicate = detectDuplicateIncident(
      {
        id: item.id,
        category: item.category,
        title: item.title,
        description: item.description,
        location: item.location,
        latitude: item.latitude,
        longitude: item.longitude,
        createdAt: item.createdAt,
      },
      result
    );

    result.push({
      ...item,
      severity: intel.recommendedSeverity,
      recommendedSeverity: intel.recommendedSeverity,
      severityReasoning: intel.severityReasoning,
      severityOverridden: false,
      priorityScore: intel.priorityScore,
      priorityFactors: intel.priorityFactors,
      duplicateWarning: duplicate,
    });
  }

  return result;
}
